    KD.hindiSentenceRows().forEach(function (row) { kept += row.tokens.length; });
    var raw = 0;
    KD.HI_SENTENCES.forEach(function (s) { raw += s.split(/\s+/).filter(Boolean).length; });
    return { kept: kept, raw: raw, lines: KD.HI_SENTENCES.length };
