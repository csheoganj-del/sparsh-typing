  function shuffle(list, random) {
    var rng = random || Math.random;
    var a = list.slice();
    for (var i = a.length - 1; i > 0; i--) {
      var j = Math.min(i, Math.max(0, Math.floor(rng() * (i + 1))));
      var t = a[i];
      a[i] = a[j];
      a[j] = t;
    }
    return a;
  }

  var cachedText = '', cachedRows = [];
  KD.hindiSentenceRows = function () {
    var text = KD.HI_SENTENCES.join('\n');
    if (text === cachedText) return cachedRows;
    var seen = {};
    cachedRows = [];
    KD.HI_SENTENCES.forEach(function (sentence) {
      var id = String(sentence).trim().replace(/\s+/g, ' ');
      if (!id.endsWith('।') || seen[id]) return;
      var tokens = id.split(' ').map(function (h) { return KD.safeToken(h); });
      // Reject a whole unsupported sentence; dropping a word changes its meaning.
      if (!tokens.length || tokens.some(function (t) { return !t; })) return;
      seen[id] = true;
      var steps = KD.buildSteps(tokens);
      cachedRows.push({ id: id, tokens: tokens, actions: steps.length,
        actionIds: Array.from(new Set(steps.map(function (step) { return step.code + (step.shift ? '+S' : ''); }))) });
    });
    cachedText = text;
    return cachedRows;
  };
  KD.hindiPassageActions = function () {
    var seen = {};
    KD.hindiSentenceRows().forEach(function (row) { row.actionIds.forEach(function (id) { seen[id] = true; }); });
    return Object.keys(seen);
  };

  KD.mergeSentenceUsage = function (a, b) {
    var usage = {};
    [a, b].forEach(function (source) {
      Object.keys(source || {}).forEach(function (id) {
        var row = source[id];
        if (!row || typeof row !== 'object') return;
        var old = usage[id] || { count: 0, at: 0 };
        usage[id] = { count: Math.max(old.count, Number(row.count) || 0), at: Math.max(old.at, Number(row.at) || 0) };
      });
    });
    return usage;
  };

  KD.selectHindiPassage = function (options) {
    options = options || {};
    var rng = options.random || Math.random, usage = options.sentenceUsage || {};
    var rows = KD.hindiSentenceRows().map(function (row) {
      return { row: row, used: usage[row.id] || { count: 0, at: 0 }, tie: rng() };
    });
    rows.sort(function (a, b) {
      return (a.used.count - b.used.count) || (a.used.at - b.used.at) || (a.tie - b.tie);
    });
    var tokens = [], sentenceIds = [], actions = 0;
    var count = Math.max(1, Number(options.count) || 400), minActions = Math.max(0, Number(options.minActions) || 0);
    // Exhaust all available sentences before beginning another cycle. Normal
    // speed checks require only a small fraction of this bank.
    for (var cycle = 0; cycle < 12 && rows.length && (tokens.length < count || actions < minActions); cycle++) {
      for (var i = 0; i < rows.length && (tokens.length < count || actions < minActions); i++) {
        var row = rows[i].row;
        sentenceIds.push(row.id);
        row.tokens.forEach(function (t) { tokens.push({ h: t.h, k: t.k, lang: 'hi' }); });
        actions += row.actions + (tokens.length > row.tokens.length ? 1 : 0);
      }
    }
    return { tokens: tokens, sentenceIds: sentenceIds, source: 'practice-pool' };
  };

  KD.buildHindiPassage = function (count, options) {
    return KD.selectHindiPassage(Object.assign({}, options || {}, { count: count })).tokens;
  };

  KD.buildEnglishPassage = function (count) {
    var words = [];
    var guard = 0;
    while (words.length < count && guard < 12) {
      shuffle(KD.EN_SENTENCES).forEach(function (line) {
        line.split(/\s+/).forEach(function (w) {
          if (w) words.push(w);
        });
      });
      guard++;
    }
    return words.slice(0, count).map(function (w) {
      return { h: w, k: w, lang: "en" };
    });
  };

